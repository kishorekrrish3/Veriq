"""Run management, event streaming (SSE), ledger inspection, and artifact retrieval endpoints.
"""

import json
import uuid
from typing import List, Optional
from fastapi import APIRouter, HTTPException, Query, Response, Request
from fastapi.responses import StreamingResponse, PlainTextResponse
from app.schemas.runs import RunCreate, RunResponse, RunStatus
from app.schemas.events import RunEvent
from app.schemas.evidence import VerificationLedgerSummary
from app.storage.repositories import RunRepository, EventRepository, LedgerRepository
from app.services.orchestrator import orchestrator
from app.services.report_generator import report_generator
from app.services.metrics import metrics_service

router = APIRouter(tags=["runs"])


@router.post("/runs", response_model=RunResponse)
async def create_run(payload: RunCreate):
    """Initializes and launches a new evidence-driven engineering run."""
    run_id = f"RUN-{uuid.uuid4().hex[:8].upper()}"

    await orchestrator.start_run(
        run_id=run_id,
        title=payload.title,
        description=payload.description,
        sample_name=payload.sample_name,
        enable_research=payload.enable_research,
        max_repair_attempts=payload.max_repair_attempts,
        mode=payload.mode,
    )

    run = RunRepository.get_run(run_id)
    if not run:
        raise HTTPException(status_code=500, detail="Failed to initialize run record")
    return run


@router.get("/runs", response_model=List[RunResponse])
async def list_runs(limit: int = Query(default=50, ge=1, le=100)):
    """Retrieves persisted engineering runs ordered by creation time."""
    return RunRepository.list_runs(limit=limit)


@router.get("/runs/{run_id}", response_model=RunResponse)
async def get_run(run_id: str):
    """Retrieves complete details, status, and telemetry for a specific run."""
    run = RunRepository.get_run(run_id)
    if not run:
        raise HTTPException(status_code=404, detail=f"Run '{run_id}' not found")
    return run


@router.get("/runs/{run_id}/events")
async def stream_run_events(run_id: str, request: Request):
    """Streams live execution events via Server-Sent Events (SSE)."""
    run = RunRepository.get_run(run_id)
    if not run:
        raise HTTPException(status_code=404, detail=f"Run '{run_id}' not found")

    async def event_generator():
        # First send all historical events
        past_events = EventRepository.get_events(run_id)
        for ev in past_events:
            yield f"data: {json.dumps(ev.model_dump())}\n\n"

        # If run is already terminal, we're done
        if run.status in (RunStatus.COMPLETED, RunStatus.FAILED, RunStatus.CANCELLED, RunStatus.VERIFICATION_FAILED):
            return

        # Otherwise listen for live events
        queue = orchestrator.subscribe(run_id)
        try:
            while True:
                if await request.is_disconnected():
                    break
                try:
                    event = await queue.get()
                    yield f"data: {json.dumps(event.model_dump())}\n\n"
                    if event.event_type.value in ("RUN_COMPLETED", "RUN_FAILED", "RUN_CANCELLED"):
                        break
                except Exception:
                    break
        finally:
            orchestrator.unsubscribe(run_id, queue)

    return StreamingResponse(
        event_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no",
        },
    )


@router.get("/runs/{run_id}/ledger", response_model=VerificationLedgerSummary)
async def get_run_ledger(run_id: str):
    """Retrieves the complete Verification Ledger with claims and backing evidence."""
    run = RunRepository.get_run(run_id)
    if not run:
        raise HTTPException(status_code=404, detail=f"Run '{run_id}' not found")
    return LedgerRepository.get_summary(run_id)


@router.get("/runs/{run_id}/diff", response_class=PlainTextResponse)
async def get_run_diff(run_id: str):
    """Retrieves the unified diff generated by the run."""
    run = RunRepository.get_run(run_id)
    if not run:
        raise HTTPException(status_code=404, detail=f"Run '{run_id}' not found")
    return run.unified_diff or "No modifications applied."


@router.get("/runs/{run_id}/report")
async def get_run_report(run_id: str, format: str = Query(default="markdown", pattern="^(markdown|json)$")):
    """Generates an inspectable audit report in Markdown or JSON format."""
    run = RunRepository.get_run(run_id)
    if not run:
        raise HTTPException(status_code=404, detail=f"Run '{run_id}' not found")

    ledger = LedgerRepository.get_summary(run_id)

    if format == "markdown":
        md = report_generator.generate_markdown_report(run, ledger)
        return PlainTextResponse(
            content=md,
            media_type="text/markdown",
            headers={"Content-Disposition": f"attachment; filename=veriq-report-{run_id}.md"},
        )
    else:
        return report_generator.generate_json_report(run, ledger)


@router.post("/runs/{run_id}/cancel")
async def cancel_run(run_id: str):
    """Cancels an active engineering run."""
    run = RunRepository.get_run(run_id)
    if not run:
        raise HTTPException(status_code=404, detail=f"Run '{run_id}' not found")

    if run.status in (RunStatus.COMPLETED, RunStatus.FAILED, RunStatus.CANCELLED):
        return {"message": f"Run '{run_id}' is already in terminal state {run.status.value}"}

    RunRepository.update_run_status(run_id, RunStatus.CANCELLED, error_message="Cancelled by user request.")
    await orchestrator.emit_event(
        run_id,
        EventType.RUN_CANCELLED,
        "Run execution cancelled by user request.",
    )
    return {"message": f"Run '{run_id}' successfully cancelled"}


@router.get("/metrics/overview")
async def get_metrics_overview():
    """Returns actual operational metrics aggregated strictly from SQLite database records."""
    return metrics_service.get_overview_statistics()
